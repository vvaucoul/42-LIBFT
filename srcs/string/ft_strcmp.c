#include <libft.h>

int ft_strcmp(const char *str, const char *str2)
{
    unsigned int i;

    i = 0;
    while (str[i] && str[i] == str2[i])
        ++i;
    return ((unsigned char)str[i] - (unsigned char)str2[i]);
}
