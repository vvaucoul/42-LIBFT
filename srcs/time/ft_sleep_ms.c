#include <libft.h>

/* Built on nanosleep() rather than usleep(), which has unspecified
** behavior for delays >= 1 second on some platforms. */
void ft_sleep_ms(unsigned int ms)
{
    struct timespec ts;

    ts.tv_sec = ms / 1000;
    ts.tv_nsec = (long)(ms % 1000) * 1000000L;
    nanosleep(&ts, NULL);
}
