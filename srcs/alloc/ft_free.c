#include "libft.h"

/*
** Takes a pointer-to-pointer so the caller's own pointer is nulled out
** after freeing, preventing a dangling pointer at the call site.
*/
void ft_free(void **ptr)
{
    if (ptr && *ptr)
    {
        free(*ptr);
        *ptr = NULL;
    }
}
